"""Bayesian network for the Meridian Drive Systems supply-chain demo.

A ~$2.5B EV-traction-motor maker exposed to rare-earth-magnet and power-semi
supply shocks. The model is a four-layer DAG, not a flat naive-Bayes star — that
depth is the point: it exercises the things a Bayesian network is *for*.

    DRIVERS      Geo_Exposure   Supplier_Health   Route_Status
                      │  ╲            │   ╲            │
    MECHANISMS     Magnet_Supply ◄────┴────► Power_Semi_Supply   (the two BOM
                          ╲                 ╱                      bottlenecks)
    LATENT              Disruption_Regime  (Normal → Severe)
                     ╱     │       ╲            ╲
    EMISSIONS  LeadTime  ForceMaj  Expedite   Input_Price_Spike ◄── Geo_Exposure
    (signals)                                  (explaining-away: macro RE pricing)
    IMPACTS    Production_Output → On_Time_Delivery     Gross_Margin_Hit
    (the $$$)                                            ↑ Production_Output

What the depth buys (none of it visible in a star):
  * Mechanism: drivers reach the regime *through* two named component
    bottlenecks (rare-earth magnets, power semiconductors). Supplier_Health is a
    shared parent of both, coupling them.
  * Explaining-away: Input_Price_Spike has the regime AND Geo_Exposure as
    parents, so a price spike under high geopolitical exposure is partly
    explained by macro rare-earth pricing and implicates the regime less.
  * Propagation to a decision: the regime drives lost production → missed OEM
    deliveries → gross-margin hit, so a headline updates a P&L-relevant node.

All CPTs are *illustrative elicited anchors* (Plan: to be calibrated via the
elicitation pipeline). The multi-parent CPTs (mechanisms, latent, price spike,
margin hit) are generated by the ranked-node method (src.cpt_builders) from a few
weights + anchor distributions, not hand-filled cell by cell.
"""
