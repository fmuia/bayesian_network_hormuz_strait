_S = "Disruption_Regime"
_DRIVERS = ["Geo_Exposure", "Supplier_Health", "Route_Status"]
_MECHANISMS = ["Magnet_Supply", "Power_Semi_Supply"]
# Regime-only emissions; Input_Price_Spike is handled separately (it also has a
# direct Geo_Exposure parent — the explaining-away edge).
_REGIME_EMISSIONS = ["Lead_Time_Slippage", "Force_Majeure_Notices", "Expedite_Spend"]
# The nodes the translator can set evidence on (the "read surface").
_EMISSIONS = _REGIME_EMISSIONS + ["Input_Price_Spike"]
_IMPACTS = ["Production_Output", "On_Time_Delivery", "Gross_Margin_Hit"]

EDGES_LATENT: List[Tuple[str, str]] = (
    # drivers → mechanisms
    [("Geo_Exposure", "Magnet_Supply"), ("Supplier_Health", "Magnet_Supply"),
     ("Route_Status", "Power_Semi_Supply"), ("Supplier_Health", "Power_Semi_Supply")]
    # mechanisms → regime
    + [(m, _S) for m in _MECHANISMS]
    # regime → emissions
    + [(_S, e) for e in _REGIME_EMISSIONS]
    + [(_S, "Input_Price_Spike"), ("Geo_Exposure", "Input_Price_Spike")]  # explaining-away
    # regime → impacts → downstream impacts
    + [(_S, "Production_Output"), ("Production_Output", "On_Time_Delivery"),
       (_S, "Gross_Margin_Hit"), ("Production_Output", "Gross_Margin_Hit")]
    # driver indicator
    + [("Geo_Exposure", "Policy_Headlines")]
)
# Meridian ships a single (latent-regime) topology; expose the same edges as the
# "labelling" alias so engine code that references either name works.
EDGES = EDGES_LATENT


def _cpd(var: str, parents: Sequence[str], table: Dict[Tuple[str, ...], Sequence[float]]) -> TabularCPD:
    """{parent-state-tuple: child-prob-vector} → TabularCPD (canonical column order)."""
    var_states = STATES[var]
    parent_states = [STATES[p] for p in parents]
    parent_cards = [len(s) for s in parent_states]
    columns = list(product(*parent_states)) if parents else [()]
    values: List[List[float]] = [[0.0] * len(columns) for _ in var_states]
    for col_idx, key in enumerate(columns):
        probs = table[key] if parents else table[()]
        if abs(sum(probs) - 1.0) > 1e-8:
            raise ValueError(f"CPT column for {var}{key} sums to {sum(probs)}")
        for row_idx, p in enumerate(probs):
            values[row_idx][col_idx] = p
    state_names = {var: var_states}
    for p, s in zip(parents, parent_states):
        state_names[p] = s
    return TabularCPD(
        variable=var, variable_card=len(var_states), values=values,
        evidence=list(parents) if parents else None,
        evidence_card=parent_cards if parents else None, state_names=state_names,
    )


