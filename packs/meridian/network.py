def build_network(topology: str = "latent_regime") -> DiscreteBayesianNetwork:
    """Assemble the Meridian latent-regime network. ``topology`` accepts
    ``"latent_regime"`` (default) or its ``"labelling"`` alias — Meridian ships a
    single topology."""
    if topology not in ("latent_regime", "labelling"):
        raise ValueError(f"Unknown topology {topology!r}; Meridian has one topology.")
    net = DiscreteBayesianNetwork(EDGES_LATENT)
    cpds = [_cpd(d, (), {(): _PRIORS[d]}) for d in _DRIVERS]

    # mechanism layer
    cpds.append(_cpd("Magnet_Supply", ("Geo_Exposure", "Supplier_Health"), ranked_node_cpt(
        ["Geo_Exposure", "Supplier_Health"], STATES, _MAGNET_WEIGHTS,
        STATES["Magnet_Supply"], _MECH_ANCHORS,
    )))
    cpds.append(_cpd("Power_Semi_Supply", ("Route_Status", "Supplier_Health"), ranked_node_cpt(
        ["Route_Status", "Supplier_Health"], STATES, _POWER_SEMI_WEIGHTS,
        STATES["Power_Semi_Supply"], _MECH_ANCHORS,
    )))

    # latent regime ← mechanisms
    cpds.append(_cpd(_S, _MECHANISMS, ranked_node_cpt(
        _MECHANISMS, STATES, _LATENT_WEIGHTS, STATES[_S], _LATENT_ANCHORS,
    )))

    # regime-only emissions
    for emission in _REGIME_EMISSIONS:
        table = {(r,): row for r, row in zip(STATES[_S], _EMISSION_TABLES[emission])}
        cpds.append(_cpd(emission, (_S,), table))

    # explaining-away emission
    cpds.append(_cpd("Input_Price_Spike", (_S, "Geo_Exposure"), ranked_node_cpt(
        [_S, "Geo_Exposure"], STATES, _PRICE_WEIGHTS,
        STATES["Input_Price_Spike"], _PRICE_ANCHORS,
    )))

    # impact layer
    prod_table = {(r,): row for r, row in zip(STATES[_S], _PRODUCTION_TABLE)}
    cpds.append(_cpd("Production_Output", (_S,), prod_table))
    cpds.append(_cpd("On_Time_Delivery", ("Production_Output",), _OTD_TABLE))
    cpds.append(_cpd("Gross_Margin_Hit", (_S, "Production_Output"), ranked_node_cpt(
        [_S, "Production_Output"], STATES, _MARGIN_WEIGHTS,
        STATES["Gross_Margin_Hit"], _MARGIN_ANCHORS,
    )))

    # driver indicator
    cpds.append(_cpd("Policy_Headlines", ("Geo_Exposure",), _POLICY_TABLE))

    net.add_cpds(*cpds)
    net.check_model()
    return net


